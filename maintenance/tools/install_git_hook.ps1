# Install a pre-commit hook that refreshes the research artifact ledger.
#
# Usage (run inside the repository root):
#   powershell -ExecutionPolicy Bypass -File maintenance\tools\install_git_hook.ps1
#
# Kept ASCII-only on purpose: Windows PowerShell 5.1 reads BOM-less .ps1
# files using the system ANSI code page, which mangles non-ASCII text.

param(
    [string]$RepoPath = (Get-Location).Path
)

$ErrorActionPreference = "Stop"

$git = Get-Command git -ErrorAction SilentlyContinue
if (-not $git) { Write-Error "git not found"; exit 1 }

Push-Location $RepoPath
try {
    $topLines = @(& git rev-parse --show-toplevel 2>$null)
    if ($LASTEXITCODE -ne 0 -or $topLines.Count -eq 0) {
        Write-Error "$RepoPath is not a git repository (run 'git init' first)"
        exit 1
    }
    [string]$top = ([string]$topLines[0]).Trim() -replace '\\', '/'

    $prefixLines = @(& git rev-parse --show-prefix 2>$null)
    [string]$rel = ""
    if ($prefixLines.Count -gt 0) {
        $rel = ([string]$prefixLines[0]).Trim() -replace '\\', '/'
    }

    $hookDir = Join-Path $RepoPath ".git\hooks"
    if (-not (Test-Path -LiteralPath $hookDir)) {
        New-Item -ItemType Directory -Force -Path $hookDir | Out-Null
    }

    # Locate a Python interpreter without hardcoding one machine's layout.
    $candidates = @()
    $onPath = Get-Command python -ErrorAction SilentlyContinue
    if ($onPath) { $candidates += $onPath.Source }
    $candidates += (Join-Path $env:USERPROFILE ".cache\codex-runtimes\codex-primary-runtime\dependencies\python\python.exe")
    [string]$py = ""
    foreach ($c in $candidates) {
        if (Test-Path -LiteralPath $c) { $py = $c -replace '\\', '/'; break }
    }
    if (-not $py) { $py = "python" }
    [string]$script = "$top/maintenance/tools/artifact_ledger.py"
    [string]$ledger = "$rel" + "maintenance/records/ARTIFACT_LEDGER.md"
    [string]$ledgerCsv = "$rel" + "maintenance/records/ARTIFACT_LEDGER.csv"

    $lines = @(
        '#!/bin/sh',
        '# Generated by maintenance/tools/install_git_hook.ps1 -- do not edit by hand.',
        '# Refresh the artifact ledger and include it in this commit.',
        "PY='$py'",
        "RESEARCH_ROOT='$top'",
        "LEDGER_MIRROR=''",
        "export RESEARCH_ROOT LEDGER_MIRROR",
        '[ -f "$PY" ] || PY=python',
        ('"{0}" "{1}" --quiet >/dev/null 2>&1 || exit 0' -f '$PY', $script),
        ('git add -A -- "{0}" "{1}" 2>/dev/null || true' -f $ledger, $ledgerCsv),
        'exit 0'
    )
    # Git for Windows runs hooks through sh: CRLF would break the shebang.
    $hook = ($lines -join "`n") + "`n"

    $hookPath = Join-Path $hookDir "pre-commit"
    [System.IO.File]::WriteAllText($hookPath, $hook, (New-Object System.Text.UTF8Encoding($false)))
    Write-Host "Installed pre-commit hook: $hookPath"
    Write-Host "Repository root: $top"
}
finally {
    Pop-Location
}
